/**
 * Build-time content generation script.
 * Reads markdown files and generates a TypeScript module with HTML content.
 *
 * Usage: bun scripts/build-content.ts
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { markdownToHtml } from './markdown.js';

const SITE_DIR = resolve(dirname(import.meta.path), '..');
const CONTENT_DIR = resolve(SITE_DIR, 'content');
const OUT_DIR = resolve(SITE_DIR, 'src', 'generated');

// Route mapping: content filename → content key
const routeMap: Array<[string, string]> = [
  ['getting-started.md', 'getting-started'],
  ['user-guide.md', 'user-guide'],
  ['charts.md', 'charts'],
  ['encryption.md', 'encryption'],
  ['cli.md', 'cli'],
  ['editor.md', 'editor'],
  ['report-binary.md', 'report-binary'],
];

function extractTitle(markdown: string): string {
  const match = markdown.match(/^#\s+(.+)/m);
  return match ? match[1].trim() : 'Untitled';
}

// Build reverse map for link rewriting
const fileToRoute = new Map<string, string>();
for (const [filename, key] of routeMap) {
  fileToRoute.set(filename, `#/${key}`);
}

const GITHUB_BASE = 'https://github.com/asymmetric-effort/go-notebook/blob/main/';

/**
 * Rewrite links in generated HTML:
 * - Relative .md links → hash routes (#/route)
 * - External links left as-is
 * - Hash links within the same page (#/something) left as-is
 */
function rewriteLinks(html: string): string {
  return html.replace(/href="([^"]+)"/g, (_match, href: string) => {
    // Skip external links and already-hash links
    if (href.startsWith('http://') || href.startsWith('https://') || href.startsWith('#')) {
      return `href="${href}"`;
    }

    // Strip anchor fragments for lookup
    const anchorIdx = href.indexOf('#');
    const anchor = anchorIdx !== -1 ? href.slice(anchorIdx) : '';
    const pathOnly = anchorIdx !== -1 ? href.slice(0, anchorIdx) : href;

    if (pathOnly === '') {
      return `href="${href}"`;
    }

    // Check if this is a known content file
    if (fileToRoute.has(pathOnly)) {
      return `href="${fileToRoute.get(pathOnly)!}${anchor}"`;
    }

    // Unresolved — point to GitHub as fallback
    return `href="${GITHUB_BASE}${pathOnly}"`;
  });
}

function main(): void {
  if (!existsSync(OUT_DIR)) {
    mkdirSync(OUT_DIR, { recursive: true });
  }

  const entries: Record<string, { title: string; html: string }> = {};

  for (const [filename, key] of routeMap) {
    const fullPath = resolve(CONTENT_DIR, filename);
    if (!existsSync(fullPath)) {
      console.warn(`Warning: ${filename} not found, skipping.`);
      continue;
    }

    const markdown = readFileSync(fullPath, 'utf-8');
    const title = extractTitle(markdown);
    const rawHtml = markdownToHtml(markdown);
    const html = rewriteLinks(rawHtml);

    entries[key] = { title, html };
    console.log(`  ${key}: "${title}" (${html.length} bytes)`);
  }

  // Generate TypeScript module
  const tsContent = `// Auto-generated by scripts/build-content.ts — do not edit manually.
export const content: Record<string, { title: string; html: string }> = ${JSON.stringify(entries, null, 2)};
`;

  const outPath = resolve(OUT_DIR, 'content.ts');
  writeFileSync(outPath, tsContent, 'utf-8');

  // Also write JSON for vite.config.ts noscript plugin consumption
  const jsonPath = resolve(OUT_DIR, 'content.json');
  writeFileSync(jsonPath, JSON.stringify(entries, null, 2), 'utf-8');

  console.log(`\nGenerated ${outPath} with ${Object.keys(entries).length} pages.`);
}

main();
